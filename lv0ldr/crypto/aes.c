#define MASK3 ((vec_uchar16)spu_maskb(0x000f))

int aes_set_encrypt_key(vec_uchar16 *rk, const unsigned char *key, int bits)
{
    vec_uchar16 s0 = sbox[0], s1 = sbox[1], s2 = sbox[2], s3 = sbox[3];
    vec_uchar16 s4 = sbox[4], s5 = sbox[5], s6 = sbox[6], s7 = sbox[7];
    vec_uchar16 s8 = sbox[8], s9 = sbox[9], s10 = sbox[10], s11 = sbox[11];
    vec_uchar16 s12 = sbox[12], s13 = sbox[13], s14 = sbox[14], s15 = sbox[15];
    vec_uchar16 tmp[16];
    int i;

    switch (bits) {
    case 128: {
        vec_uchar16 k0, t, s, n;
        vec_uchar16 c, w0, w1, w2;

        k0 = *(const vec_uchar16 *)key;
        rk[0] = k0;
        c = (vec_uchar16)spu_splats(0x0d0e0f0cu);
        w0 = W0;
        w1 = W1X;
        w2 = W2X;
        for (i = 0; i < 10; i++) {
            t = spu_shuffle(k0, ZERO, c);
            SUBBYTES(s, t);
            n = spu_xor(spu_xor(spu_xor(spu_shuffle(k0, ZERO, w0), spu_shuffle(k0, ZERO, w1)),
                                spu_xor(spu_shuffle(k0, ZERO, w2), spu_and(k0, MASK3))),
                        spu_xor((vec_uchar16)rcon[i], s));
            rk[i + 1] = n;
            k0 = n;
        }
        return 10;
    }
    case 192: {
        vec_uchar16 k0, k1, t, s, n, u, m, v;
        vec_uchar16 w1, p12, c, w0, w2, m3, p10;

        w1 = W1X;
        c = (vec_uchar16)spu_splats(0x15161714u);
        w0 = W0;
        w2 = W2X;
        m3 = MASK3;
        p10 = ((vec_uchar16){0x10,0x11,0x12,0x13, 0x10,0x11,0x12,0x13, 0x80,0x80,0x80,0x80, 0x80,0x80,0x80,0x80});
        p12 = ((vec_uchar16){12,13,14,15, 12,13,14,15, 0x80,0x80,0x80,0x80, 0x80,0x80,0x80,0x80});
        k0 = ((const vec_uchar16 *)key)[0];
        k1 = ((const vec_uchar16 *)key)[1];
        i = 0;
        for (;;) {
            tmp[2 * i] = k0;
            tmp[2 * i + 1] = k1;
            t = spu_shuffle(k0, k1, c);
            SUBBYTES(s, t);
            n = spu_xor(spu_xor(spu_xor(spu_shuffle(k0, ZERO, w0), spu_shuffle(k0, ZERO, w1)),
                                spu_xor(spu_shuffle(k0, ZERO, w2), spu_and(k0, m3))),
                        spu_xor((vec_uchar16)rcon[i], s));
            t = spu_shuffle(k0, k1, p10);
            m = spu_and(k1, (vec_uchar16)spu_maskb(0x0f00));
            i++;
            if (i == 8)
                break;
            v = spu_xor(t, m);
            k0 = n;
            u = spu_xor(spu_shuffle(n, u, p12), v);
            k1 = u;
        }
        for (i = 0; i < 4; i++) {
            rk[3 * i] = tmp[4 * i];
            rk[3 * i + 1] = spu_shuffle(tmp[4 * i + 1], tmp[4 * i + 2], ((vec_uchar16){0,1,2,3, 4,5,6,7, 0x10,0x11,0x12,0x13, 0x14,0x15,0x16,0x17}));
            rk[3 * i + 2] = spu_shuffle(tmp[4 * i + 2], tmp[4 * i + 3], ((vec_uchar16){8,9,10,11, 12,13,14,15, 0x10,0x11,0x12,0x13, 0x14,0x15,0x16,0x17}));
        }
        rk[12] = n;
        return 12;
    }
    case 256: {
        vec_uchar16 k0, k1, t, s, n, sel;
        vec_uchar16 c1, c2, w0, w1, m3;

        k0 = ((const vec_uchar16 *)key)[0];
        k1 = ((const vec_uchar16 *)key)[1];
        rk[0] = k0;
        rk[1] = k1;
        n = k1;
        sel = ZERO;
        c1 = (vec_uchar16)spu_splats(0x1d1e1f1cu);
        c2 = (vec_uchar16)spu_splats(0x1c1d1e1fu);
        w0 = W0;
        w1 = W1X;
        m3 = MASK3;
        for (i = 0; i < 13; i++) {
            t = spu_sel(spu_shuffle(ZERO, n, c1), spu_shuffle(ZERO, n, c2), sel);
            SUBBYTES(s, t);
            n = spu_xor(spu_xor(spu_xor(spu_shuffle(k0, ZERO, w0), spu_shuffle(k0, ZERO, w1)),
                                spu_xor(spu_shuffle(k0, ZERO, W2X), spu_and(k0, m3))),
                        spu_xor(spu_andc((vec_uchar16)rcon[i / 2], sel), s));
            k0 = k1;
            k1 = n;
            rk[i + 2] = n;
            sel = spu_xor(sel, (unsigned char)0xff);
        }
        return 14;
    }
    }
    return -1;
}

int aes_set_decrypt_key(vec_uchar16 *rk, const unsigned char *key, int bits)
{
    vec_uchar16 tmp[15];
    int nr, i;

    nr = aes_set_encrypt_key(tmp, key, bits);
    if (nr < 0)
        return nr;
    rk[0] = tmp[0];
    rk[1] = spu_shuffle(tmp[1], ZERO, SR0);
    rk[2] = spu_shuffle(tmp[2], ZERO, SR0);
    rk[3] = spu_shuffle(tmp[3], ZERO, SR0);
    rk[4] = spu_shuffle(tmp[4], ZERO, SR0);
    rk[5] = spu_shuffle(tmp[5], ZERO, SR0);
    rk[6] = spu_shuffle(tmp[6], ZERO, SR0);
    rk[7] = spu_shuffle(tmp[7], ZERO, SR0);
    rk[8] = spu_shuffle(tmp[8], ZERO, SR0);
    rk[9] = spu_shuffle(tmp[9], ZERO, SR0);
    rk[nr] = tmp[nr];
    for (i = 10; i < nr; i++)
        rk[i] = spu_shuffle(tmp[i], ZERO, SR0);
    return nr;
}

int aes_encrypt_block(vec_uchar16 *out, const vec_uchar16 *in, const vec_uchar16 *rk, int nr)
{
    vec_uchar16 s0 = sbox[0], s1 = sbox[1], s2 = sbox[2], s3 = sbox[3];
    vec_uchar16 s4 = sbox[4], s5 = sbox[5], s6 = sbox[6], s7 = sbox[7];
    vec_uchar16 s8 = sbox[8], s9 = sbox[9], s10 = sbox[10], s11 = sbox[11];
    vec_uchar16 s12 = sbox[12], s13 = sbox[13], s14 = sbox[14], s15 = sbox[15];
    vec_uchar16 sr0 = SR0, sr1 = SR1, sr2 = SR2, sr3 = SR3;
    vec_uchar16 x, s, x2, x3, t2, t3;
    int r;

    x = spu_xor(*in, *rk++);
    for (r = 1; r < nr; r++) {
        SUBBYTES(s, x);
        t2 = spu_shuffle(s, ZERO, sr2);
        t3 = spu_shuffle(s, ZERO, sr3);
        x2 = spu_xor(spu_and((vec_uchar16)spu_slqw((vec_uint4)s, 1), (unsigned char)0xfe),
                     spu_and((vec_uchar16)spu_cmpgt(s, (unsigned char)0x7f), (unsigned char)0x1b));
        x3 = spu_xor(x2, s);
        x = spu_xor(*rk++, spu_xor(spu_xor(spu_shuffle(x2, ZERO, sr0), spu_shuffle(x3, ZERO, sr1)),
                                   spu_xor(t2, t3)));
    }
    SUBBYTES(s, x);
    *out = spu_xor(spu_shuffle(s, ZERO, sr0), *rk);
    return 0;
}
#define T2 ((vec_uchar16){0x00,0x40,0x80,0xc0,0x1b,0x5b,0x9b,0xdb,0x00,0x40,0x80,0xc0,0x1b,0x5b,0x9b,0xdb})

#define ENC_SUB(i) do { \
        SUBBYTES(s, b##i); \
        hi = spu_and((vec_uchar16)spu_rlmaskqw((vec_uint4)s, -5), (unsigned char)7); \
        x2_##i = spu_xor(spu_and((vec_uchar16)spu_slqw((vec_uint4)s, 1), (unsigned char)0x3e), spu_shuffle(T2, T2, hi)); \
        x3_##i = spu_xor(x2_##i, s); \
        u_##i = spu_xor(spu_shuffle(s, ZERO, sr2), spu_shuffle(s, ZERO, sr3)); \
    } while (0)
#define ENC_ROT(i) x2_##i = spu_shuffle(x2_##i, ZERO, sr0)
#define ENC_MIX(i) b##i = spu_xor(k, spu_xor(spu_xor(x2_##i, spu_shuffle(x3_##i, ZERO, sr1)), u_##i))
#define ENC_LAST(o, x) do { \
        SUBBYTES(s, x); \
        o = spu_xor(spu_shuffle(s, ZERO, sr0), k); \
    } while (0)

int aes_encrypt8(vec_uchar16 *out, const vec_uchar16 *in, const vec_uchar16 *rk, int nr)
{
    vec_uchar16 s0 = sbox[0], s1 = sbox[1], s2 = sbox[2], s3 = sbox[3];
    vec_uchar16 s4 = sbox[4], s5 = sbox[5], s6 = sbox[6], s7 = sbox[7];
    vec_uchar16 s8 = sbox[8], s9 = sbox[9], s10 = sbox[10], s11 = sbox[11];
    vec_uchar16 s12 = sbox[12], s13 = sbox[13], s14 = sbox[14], s15 = sbox[15];
    vec_uchar16 sr0 = SR0, sr1 = SR1, sr2 = SR2, sr3 = SR3;
    vec_uchar16 b0, b1, b2, b3, b4, b5, b6, b7;
    vec_uchar16 x2_0, x2_1, x2_2, x2_3, x2_4, x2_5, x2_6, x2_7;
    vec_uchar16 x3_0, x3_1, x3_2, x3_3, x3_4, x3_5, x3_6, x3_7;
    vec_uchar16 u_0, u_1, u_2, u_3, u_4, u_5, u_6, u_7;
    vec_uchar16 k, s, hi;
    int r;

    k = *rk++;
    b0 = spu_xor(in[0], k);
    b1 = spu_xor(in[1], k);
    b2 = spu_xor(in[2], k);
    b3 = spu_xor(in[3], k);
    b4 = spu_xor(in[4], k);
    b5 = spu_xor(in[5], k);
    b6 = spu_xor(in[6], k);
    b7 = spu_xor(in[7], k);
    for (r = 1; r < nr; r++) {
        k = *rk++;
        ENC_SUB(0); ENC_SUB(1); ENC_SUB(2); ENC_SUB(3);
        ENC_SUB(4); ENC_SUB(5); ENC_SUB(6); ENC_SUB(7);
        ENC_ROT(0); ENC_ROT(1); ENC_ROT(2); ENC_ROT(3);
        ENC_ROT(4); ENC_ROT(5); ENC_ROT(6); ENC_ROT(7);
        ENC_MIX(0); ENC_MIX(1); ENC_MIX(2); ENC_MIX(3);
        ENC_MIX(4); ENC_MIX(5); ENC_MIX(6); ENC_MIX(7);
    }
    k = *rk;
    ENC_LAST(out[0], b0);
    ENC_LAST(out[1], b1);
    ENC_LAST(out[2], b2);
    ENC_LAST(out[3], b3);
    ENC_LAST(out[4], b4);
    ENC_LAST(out[5], b5);
    ENC_LAST(out[6], b6);
    ENC_LAST(out[7], b7);
    return 0;
}

