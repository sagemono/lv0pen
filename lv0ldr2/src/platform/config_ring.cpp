bool is_spu_enabled(u64 spu)
{
    if (spu > 7)
        return 0;
    return (read32(0x20000509C38ULL) & 0xFF) & (128 >> spu);
}

unsigned int get_spu_vr(u64 spu)
{
    return read64(0x20000400020ULL + (spu << 13));
}

bool config_ring::cmp_bits(const unsigned char *a, const unsigned char *b, unsigned short start,
                           unsigned short count, int offset)
{
    unsigned int i = start >> 3;
    unsigned short bit = start & 7;

    while (count) {
        int m = 1 << (7 - bit);
        if ((a[i] & m) != (b[i] & m)) {
            log_message("[ERROR]: config_ring cmp fail bit %d, actual 0x%02x, expect 0x%02x\n",
                        i * 8 + bit - offset, a[i], b[i]);
            return 0;
        }
        bit++;
        if (bit > 7) {
            bit = 0;
            i++;
        }
        count--;
    }
    return 1;
}

u64 get_first_spu(void)
{
    u64 i = 0;

    do {
        if (is_spu_enabled(i))
            break;
        i++;
    } while (i != 8);
    return i;
}

unsigned int get_first_spu_vr(void)
{
    return get_spu_vr(get_first_spu());
}

long config_ring::verify(void)
{
    int len;
    int offset;
    unsigned int header;
    const unsigned char *expected;
    const unsigned short *vary;
    unsigned int vr = get_first_spu_vr();
    int i;

    switch (vr) {
    default:
        len = 342;
        header = 166;
        offset = 0;
        expected = config_ring_expected_2;
        vary = config_ring_vary_2;
        break;
    case 513:
    case 514:
        len = 338;
        offset = 3;
        header = 187;
        expected = config_ring_expected;
        vary = config_ring_vary;
        break;
    }
    for (i = 0; i != (int)(header >> 3); i++)
        spu_readch(67);

    unsigned char ring[len];

    while (len--)
        ring[len] = spu_readch(67);

    const unsigned short *p = vary;

    for (;;) {
        if (p[1] == 0xFFFF)
            return 0;
        const unsigned short *next = p + 2;
        unsigned short end = p[0] + p[1];

        if (!cmp_bits(ring, expected, end + offset, next[0] - end, offset))
            return -1;
        p = next;
    }
}
