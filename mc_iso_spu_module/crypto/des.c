int des3_set_encrypt_key(unsigned int *sk, const unsigned char *key, int bits)
{
    unsigned int t[32];
    int i;
    unsigned int *d;

    if (bits != 64 && bits != 128 && bits != 192)
        return -1;
    des_set_key(sk, key);
    if (bits == 64)
        return 1;
    des_set_key(t, key + 8);
    d = sk + 32;
    for (i = 0; i < 16; i++) {
        d[2 * i] = t[30 - 2 * i];
        d[2 * i + 1] = t[31 - 2 * i];
    }
    if (bits == 128)
        return 2;
    des_set_key(sk + 64, key + 16);
    return 3;
}

int des3_set_decrypt_key(unsigned int *sk, const unsigned char *key, int bits)
{
    unsigned int t[32], t3[32];
    int i;
    unsigned int *d;

    if (bits != 64 && bits != 128 && bits != 192)
        return -1;
    des_set_key(t, key);
    d = sk;
    for (i = 0; i < 16; i++) {
        d[2 * i] = t[30 - 2 * i];
        d[2 * i + 1] = t[31 - 2 * i];
    }
    if (bits == 64)
        return 1;
    des_set_key(sk + 32, key + 8);
    if (bits == 128)
        return 2;
    for (i = 0; i < 32; i++)
        sk[64 + i] = sk[i];
    des_set_key(t3, key + 16);
    for (i = 0; i < 16; i++) {
        d[2 * i] = t3[30 - 2 * i];
        d[2 * i + 1] = t3[31 - 2 * i];
    }
    return 3;
}

#define DES_IP(X, Y) {                                            \
    T = ((X >> 4) ^ Y) & 0x0F0F0F0F; Y ^= T; X ^= (T << 4);       \
    T = ((X >> 16) ^ Y) & 0x0000FFFF; Y ^= T; X ^= (T << 16);     \
    T = ((Y >> 2) ^ X) & 0x33333333; X ^= T; Y ^= (T << 2);       \
    T = ((Y >> 8) ^ X) & 0x00FF00FF; X ^= T; Y ^= (T << 8);       \
    Y = (Y << 1) | (Y >> 31);                                     \
    T = (X ^ Y) & 0xAAAAAAAA; Y ^= T; X ^= T;                     \
    X = (X << 1) | (X >> 31);                                     \
}

#define DES_FP(X, Y) {                                            \
    X = (X << 31) | (X >> 1);                                     \
    T = (X ^ Y) & 0xAAAAAAAA; X ^= T; Y ^= T;                     \
    Y = (Y << 31) | (Y >> 1);                                     \
    T = ((Y >> 8) ^ X) & 0x00FF00FF; X ^= T; Y ^= (T << 8);       \
    T = ((Y >> 2) ^ X) & 0x33333333; X ^= T; Y ^= (T << 2);       \
    T = ((X >> 16) ^ Y) & 0x0000FFFF; Y ^= T; X ^= (T << 16);     \
    T = ((X >> 4) ^ Y) & 0x0F0F0F0F; Y ^= T; X ^= (T << 4);       \
}

#define DES_ROUND(X, Y, k) {                 \
    U = (k)[1] ^ X;                          \
    T = ((X << 30) | (X >> 2)) ^ (k)[0];     \
    Y ^= SB7[(T >> 2) & 0x3F];               \
    Y ^= SB5[(T >> 10) & 0x3F];              \
    Y ^= SB3[(T >> 18) & 0x3F];              \
    Y ^= SB1[(T >> 26) & 0x3F];              \
    Y ^= SB4[(U >> 24) & 0x3F];              \
    Y ^= SB2[(U >> 16) & 0x3F];              \
    Y ^= SB6[(U >> 8) & 0x3F];               \
    Y ^= SB8[U & 0x3F];                      \
}

static void des_rounds(unsigned int *b, const unsigned int *k)
{
    unsigned int X, Y, T, U;
    int i;

    X = b[0];
    Y = b[1];
    for (i = 0; i < 8; i++) {
        DES_ROUND(Y, X, k + 4 * i);
        DES_ROUND(X, Y, k + 4 * i + 2);
    }
    b[0] = X;
    b[1] = Y;
}

int des3_crypt_block(unsigned char *out, const unsigned char *in, const unsigned int *sk,
                     int nkeys)
{
    unsigned int b[2];
    unsigned int T;

    b[0] = GET_UINT32_BE(in, 0);
    b[1] = GET_UINT32_BE(in, 4);
    DES_IP(b[0], b[1]);
    des_rounds(b, sk);
    if (nkeys == 1) {
        DES_FP(b[1], b[0]);
        PUT_UINT32_BE(b[1], out, 0);
        PUT_UINT32_BE(b[0], out, 4);
        return 0;
    }
    T = b[0]; b[0] = b[1]; b[1] = T;
    des_rounds(b, sk + 32);
    T = b[0]; b[0] = b[1]; b[1] = T;
    if (nkeys == 2)
        des_rounds(b, sk);
    else
        des_rounds(b, sk + 64);
    DES_FP(b[1], b[0]);
    PUT_UINT32_BE(b[1], out, 0);
    PUT_UINT32_BE(b[0], out, 4);
    return 0;
}
